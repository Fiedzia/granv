use std::fs::File;
use std::io::{BufReader, Write};

use indicatif::ProgressBar;
use xml::attribute::Attribute;
use xml::reader::{EventReader, XmlEvent};
use xml::writer::EmitterConfig;
use xml::writer::EventWriter;

use crate::layouts::dirtree::svg::NodeLayout;
use crate::templates::askama::tree::dirtree::Rendered;

const XML_START: &str = "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"no\"?>\n";
const SVG_START: &str = "<svg xmlns=\"http://www.w3.org/2000/svg\">\n";
const SVG_END: &str = "</svg>\n";

///Set x and y to position main svg element, remove xml declaration
pub fn set_svg_x_y(svg: &str, x: u32, y: u32) -> Result<String, String> {
    let parser = EventReader::new(BufReader::new(svg.as_bytes()));
    let output: Vec<u8> = vec![];
    let mut writer = EventWriter::new_with_config(
        output,
        EmitterConfig::new()
            .perform_indent(true)
            .write_document_declaration(false),
    );
    let mut first_svg_element = true;
    for e in parser {
        match e {
            Ok(mut event) => {
                match event {
                    XmlEvent::StartElement {
                        ref name,
                        ref mut attributes,
                        ..
                    } => {
                        if name.local_name == "svg" && first_svg_element {
                            attributes
                                .push(Attribute::new("x".into(), &format!("{}mm", x)).to_owned());
                            attributes
                                .push(Attribute::new("y".into(), &format!("{}mm", y)).to_owned());
                        }
                        first_svg_element = false;
                        let we = event
                            .as_writer_event()
                            .ok_or_else(|| format!("svg parsing failed::{}", svg))?;
                        writer.write(we).map_err(|e| e.to_string())?;
                    }
                    XmlEvent::StartDocument { .. } => {}
                    //Some event are generated by only reader and have no equivalent for writer
                    XmlEvent::Whitespace { .. } | XmlEvent::EndDocument { .. } => {}
                    _ => {
                        let we = event
                            .as_writer_event()
                            .ok_or_else(|| format!("svg parsing failed2::{}", svg))?;
                        writer.write(we).map_err(|e| e.to_string())?;
                    }
                }
            }
            Err(e) => return Err(e.to_string()),
        }
    }
    Ok(String::from_utf8(writer.into_inner()).map_err(|e| e.to_string())?)
}

pub fn export_dirtree_svg(
    rendered_node_templates: &[Rendered],
    node_layout: &[NodeLayout],
    width: u32,
    height: u32,
    progress_bar: Option<&ProgressBar>,
) -> Result<(), String> {
    let mut file = File::create("dirtree.svg").map_err(|e| e.to_string())?;
    file.write_all(XML_START.as_bytes())
        .map_err(|e| e.to_string())?;
    file.write_all(SVG_START.as_bytes())
        .map_err(|e| e.to_string())?;
    if let Some(pb) = progress_bar {
        pb.set_length(rendered_node_templates.len() as u64);
    }
    for (idx, (tmpl, nl)) in rendered_node_templates
        .into_iter()
        .zip(node_layout)
        .enumerate()
    {
        match tmpl {
            Rendered::SVG(svg) => {
                let modified_svg = set_svg_x_y(svg, nl.left_top.0, nl.left_top.1)?;
                file.write_all(modified_svg.as_ref())
                    .map_err(|e| e.to_string())?;
            }
        }
        let cnt = 1000usize;
        if let Some(pb) = progress_bar
            && idx % cnt == 0
        {
            pb.inc(cnt as u64);
        };
    }
    file.write_all(SVG_END.as_bytes())
        .map_err(|e| e.to_string())?;

    Ok(())
}
